// Writes the short recommendation shown above the result cards, from the
// talks the search found. The LLM only words the answer: which talks are on
// now, later or over was already decided in code (lib/search.js).
const { streamChat } = require('./llm');

const ANSWER_TIMEOUT_MS = 30_000;
const VENUE_TIME_ZONE = 'America/Denver';

const SYSTEM_PROMPT = `You help attendees of KubeCon + CloudNativeCon North America 2026 pick talks.
Answer in the language of the question. Use only the talks listed in the message; never invent talks, times, rooms, speakers or facts.
The deck and page descriptions were generated by AI from the slides the speakers uploaded. Call them "slides" and cite pages like (p.12).
Keep it short enough for a phone screen: at most about 120 words, plain text, no tables or headings.
Structure:
1. Best pick now: one talk from NOW that fits the question. Give its time and room, and in one sentence why, based on its slides when there are any.
2. Also now: up to two other talks from NOW that fit, one line each.
3. Later: up to two talks from LATER that fit, one line each, with day and time.
4. If a PAST talk fits well, end with one line saying it is over and the slides or recording are worth a look later.
If nothing in NOW fits the question, say so plainly and point to LATER instead. Never recommend a talk just because it is on now.
All times are venue time (MST).`;

const timeFormat = new Intl.DateTimeFormat('en-US', { timeZone: VENUE_TIME_ZONE, weekday: 'short', hour: '2-digit', minute: '2-digit', hour12: false });
const clockFormat = new Intl.DateTimeFormat('en-US', { timeZone: VENUE_TIME_ZONE, hour: '2-digit', minute: '2-digit', hour12: false });

const venueTime = (iso) => timeFormat.format(new Date(iso));
const venueClock = (iso) => clockFormat.format(new Date(iso));

const DECK_FLAGS = {
  has_live_demo: 'live demo',
  has_experience_story: 'real-world experience',
  has_failure_story: 'failure story',
  has_measured_results: 'measured results',
};

function describe(card, n) {
  const where = [card.room, card.floor, card.venue].filter(Boolean).join(', ');
  const when = card.status === 'live' ? `on now, ${card.minutesLeft} min left`
    : card.status === 'soon' ? `starts in ${card.startsInMinutes} min`
      : card.status === 'past' ? 'already over' : 'later';
  const lines = [`[${n}] ${card.title}`, `    ${venueTime(card.start)}-${venueClock(card.end)} (${when}), ${where || 'room not listed'}`];
  const facts = [card.level && `level ${card.level}`, card.track && `track ${card.track}`, card.speakers?.length && `speakers ${card.speakers.join(', ')}`].filter(Boolean);
  if (facts.length) lines.push(`    ${facts.join('; ')}`);
  if (card.deckSummary) lines.push(`    Slides overall: ${card.deckSummary}`);
  if (card.deck) {
    const flags = Object.entries(DECK_FLAGS).filter(([k]) => card.deck[k]).map(([, v]) => v);
    if (card.deck.topology_detail && card.deck.topology_detail !== 'none') flags.push(`${card.deck.topology_detail} architecture diagrams`);
    if (card.deck.audience) flags.push(`slides read as ${card.deck.audience}`);
    if (flags.length) lines.push(`    Slides show: ${flags.join(', ')}`);
  }
  for (const p of card.pages || []) lines.push(`    Matching slide p.${p.page} (${p.type}): ${p.summary}`);
  if (!card.slides) lines.push('    No slides uploaded.');
  return lines.join('\n');
}

function buildMessages(result) {
  let n = 0;
  const section = (name, cards) => `${name}:\n${cards.length ? cards.map((c) => describe(c, ++n)).join('\n') : '(none)'}`;
  const user = [
    `Question: ${result.question}`,
    `Asked at: ${venueTime(result.at)} MST`,
    '',
    section('NOW', result.now),
    '',
    section('LATER', result.later),
    '',
    section('PAST', result.past),
  ].join('\n');
  return [
    { role: 'system', content: SYSTEM_PROMPT },
    { role: 'user', content: user },
  ];
}

function writeAnswer(client, endpoint, result, { onDelta, signal } = {}) {
  return streamChat(client, endpoint, buildMessages(result), { timeoutMs: ANSWER_TIMEOUT_MS, onDelta, signal });
}

module.exports = { writeAnswer, buildMessages, describe, SYSTEM_PROMPT };
